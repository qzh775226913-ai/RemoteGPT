#!/usr/bin/env python3
"""Deterministic Android vectors and catalog from RemoteGPT's original icon paths."""
import argparse
import json
from pathlib import Path
from xml.sax.saxutils import escape

ROOT = Path(__file__).resolve().parents[1]
RES = ROOT / 'app/src/main/res'
HEADER = '<?xml version="1.0" encoding="utf-8"?>\n'
NAMESPACE = 'xmlns:android="http://schemas.android.com/apk/res/android"'


def vector(paths, spec, launcher=False, background=False):
    size = 108 if launcher else 24
    rows = [HEADER.rstrip(), f'<vector {NAMESPACE} android:width="{size}dp" android:height="{size}dp" android:viewportWidth="{size}" android:viewportHeight="{size}">']
    if background:
        rows.append(f'    <path android:fillColor="{spec["background"]}" android:pathData="M0,0H108V108H0Z" />')
    if launcher:
        rows.append('    <group android:translateX="22.2" android:translateY="22.2" android:scaleX="2.65" android:scaleY="2.65">')
    for path in paths:
        attrs = 'android:fillColor="#FFFFFFFF"' if path.get('filled') else f'android:fillColor="@android:color/transparent" android:strokeColor="#FFFFFFFF" android:strokeWidth="{spec["strokeWidth"]}" android:strokeLineCap="round" android:strokeLineJoin="round"'
        rows.append(f'    <path {attrs} android:pathData="{escape(path["path"])}" />')
    if launcher:
        rows.append('    </group>')
    rows.append('</vector>')
    return '\n'.join(rows) + '\n'


def outputs(spec):
    result = {RES / 'drawable' / f'ic_ui_{name.lower()}.xml': vector(paths, spec) for name, paths in spec['icons'].items()}
    brand = spec['icons']['brand']
    result[RES / 'drawable/ic_notification.xml'] = vector(brand, spec)
    result[RES / 'drawable/launcher_foreground.xml'] = vector(brand, spec, launcher=True)
    result[RES / 'drawable/ic_launcher.xml'] = vector(brand, spec, launcher=True, background=True)
    result[RES / 'drawable/launcher_background.xml'] = HEADER + f'<shape {NAMESPACE} android:shape="rectangle"><solid android:color="{spec["background"]}" /></shape>\n'
    for version in (26, 33):
        monochrome = '    <monochrome android:drawable="@drawable/launcher_foreground" />\n' if version >= 33 else ''
        result[RES / f'mipmap-anydpi-v{version}/ic_launcher.xml'] = HEADER + f'<adaptive-icon {NAMESPACE}>\n    <background android:drawable="@drawable/launcher_background" />\n    <foreground android:drawable="@drawable/launcher_foreground" />\n{monochrome}</adaptive-icon>\n'
    names = ', '.join(f'"{name}"' for name in spec['icons'])
    cases = '\n'.join(f'      case "{name}": return R.drawable.ic_ui_{name.lower()};' for name in spec['icons'])
    result[ROOT / 'app/src/main/java/app/remotessh/AppIconCatalog.java'] = f'''package app.remotessh;

/** Generated by tools/generate_icons.py; edit tools/icon_spec.json instead. */
final class AppIconCatalog {{
  static final float STROKE_WIDTH = {spec['strokeWidth']}f;
  static final String[] NAMES = {{{names}}};
  static int resource(String name) {{
    switch(name) {{
{cases}
      default: return R.drawable.ic_ui_computer;
    }}
  }}
}}
'''
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    spec = json.loads((ROOT / 'tools/icon_spec.json').read_text())
    stale = []
    for path, content in outputs(spec).items():
        if args.check:
            if not path.exists() or path.read_text() != content:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
    if stale:
        raise SystemExit('Stale icon outputs: ' + ', '.join(stale))
    print(('Verified' if args.check else 'Generated') + f' {len(spec["icons"])} icons and shared launcher/notification variants')


if __name__ == '__main__':
    main()
